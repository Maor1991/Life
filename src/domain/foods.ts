/**
 * User-defined foods, loaded from the database at runtime and merged into
 * lookups so meals can reference them exactly like built-in foods.
 */
let customFoods: Food[] = [];

export function setCustomFoods(foods: Food[]): void {
  customFoods = foods;
}

export function allFoods(): Food[] {
  return [...customFoods, ...FOODS];
}

export function searchFoods(query: string, limit = 10): Food[] {
  const q = query.trim();
  if (!q) return [];
  const starts: Food[] = [];
  const contains: Food[] = [];
  for (const food of allFoods()) {
    if (food.name.startsWith(q)) starts.push(food);
    else if (food.name.includes(q) || food.aliases?.some((a) => a.includes(q))) contains.push(food);
  }
  return [...starts, ...contains].slice(0, limit);
}

export function getFoodById(id: string): Food | undefined {
  return allFoods().find((f) => f.id === id);
}

export function buildCustomFood(
  id: string,
  name: string,
  per100g: { proteinG: number; carbsG: number; fatG: number },
  servingGrams?: number
): Food {
  const portions: FoodPortion[] = [];
  if (servingGrams && servingGrams > 0) {
    portions.push({ label: 'מנה', grams: servingGrams });
  }
  portions.push({ label: '100 ג׳', grams: 100 });
  return { id, name, category: 'שלי', per100g, portions };
}

export interface MacroSet {
  proteinG: number;
  carbsG: number;
  fatG: number;
}

export function macrosForGrams(food: Food, grams: number): MacroSet {
  const factor = grams / 100;
  return {
    proteinG: food.per100g.proteinG * factor,
    carbsG: food.per100g.carbsG * factor,
    fatG: food.per100g.fatG * factor,
  };
}

export function sumMacros(items: MacroSet[]): MacroSet {
  return items.reduce(
    (acc, m) => ({
      proteinG: acc.proteinG + m.proteinG,
      carbsG: acc.carbsG + m.carbsG,
      fatG: acc.fatG + m.fatG,
    }),
    { proteinG: 0, carbsG: 0, fatG: 0 }
  );
}

/** Standard Atwater factors: protein and carbs 4 kcal/g, fat 9 kcal/g. */
export function caloriesFromMacros(m: MacroSet): number {
  return m.proteinG * 4 + m.carbsG * 4 + m.fatG * 9;
}
