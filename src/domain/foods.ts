export interface FoodPortion {
  label: string;
  grams: number;
}

export interface Food {
  id: string;
  name: string;
  aliases?: string[];
  category: string;
  /** Macros per 100 grams (edible portion; cooked where the name says so). */
  per100g: { proteinG: number; carbsG: number; fatG: number };
  /** Selectable measures. First one is the default on quick-add. */
  portions: FoodPortion[];
}

type PortionDef = [label: string, grams: number];

function f(
  id: string,
  name: string,
  category: string,
  per: [number, number, number],
  portions: PortionDef[],
  aliases?: string[]
): Food {
  return {
    id,
    name,
    category,
    aliases,
    per100g: { proteinG: per[0], carbsG: per[1], fatG: per[2] },
    portions: portions.map(([label, grams]) => ({ label, grams })),
  };
}

